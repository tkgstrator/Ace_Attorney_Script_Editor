const KANJI = '\\u4e00-\\u9fff々';
/**
 * 名前＋敬称など（人の呼び方）。
 * 頭の「お」「ご」は呼び方の一部として取る（「お姉ちゃん」を「姉ちゃん」と数えない）。
 * - 漢字・カタカナの呼び名: 直前の「お」「ご」を含める（「お姉ちゃん」「おジイさん」「ご主人さま」）
 * - ひらがなだけの呼び名: ひらがなの続きの頭から取る。ただし「のおかあさん」のように
 *   ひらがなの後に続く「お」「ご」で始まるものは、その「お」「ご」から取る（敬称は さん・ちゃん・さま・ちゃま・くん に限る）
 */
export const HONORIFIC = new RegExp(
  `((?<![${HIRA}])[${HIRA}]{2,5}|(?<=[${HIRA}])[おご][${HIRA}]{1,4}(?=さん|ちゃん|さま|ちゃま|くん)|(?:[おご](?=[${KATA}${KANJI}])|(?<![${KATA}${KANJI}]))[${KATA}${KANJI}]{1,7})(さん|くん|クン|君|ちゃん|チャン|さま|様|サマ|どの|殿|ドノ|先生|センセイ|センセ|刑事|検事|弁護士|氏|ちゃま)(?![${KATA}])`,
  'g',
);
